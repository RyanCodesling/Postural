/** Opt-in SQL acceptance for shared exercises. Uses only connection-private
 * pg_temp tables, with no public rows/default sequences copied or mutated.
 * Run with DATABASE_URL set: npm run verify:exercises:db
 */
/* eslint-disable @typescript-eslint/no-explicit-any */
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import vm from "node:vm";
import { Client } from "pg";
import ts from "typescript";
import { generateSchedule, MAX_INTERVAL_DAYS } from "../src/lib/exercises/occurrences";
import { PRESCRIPTION_SNAPSHOT_VERSION } from "../src/lib/prescriptionContext";
import { exerciseVideoFileFromRow } from "../src/lib/exercises/customVideo";

assert(process.env.DATABASE_URL, "DATABASE_URL is required for private temporary-table acceptance");
const client = new Client({ connectionString: process.env.DATABASE_URL });
const tables = ["exercises", "patient_exercises", "exercise_occurrences", "program_exercises", "exercise_programs", "sessions"];
const source = readFileSync(new URL("../src/lib/db.ts", import.meta.url), "utf8");
const names = ["getExercises", "getExerciseById", "ExerciseInUseError", "archiveExercise", "restoreExercise",
  "discardNewExercise", "deleteArchivedExercise", "setExerciseVideoFile", "canViewExerciseVideo",
  "ExerciseAssignmentNotAllowedError", "normalizeRestSeconds", "normalizeHoldSeconds", "assignExercisesToPatient",
  "ProgramExerciseNotAllowedError", "validateProgramExerciseAccess", "insertProgramExercises", "createProgram"];
const ast = ts.createSourceFile("db.ts", source, ts.ScriptTarget.Latest, true);
const nodes = ast.statements.filter(n => (ts.isFunctionDeclaration(n) || ts.isClassDeclaration(n)) && names.includes(n.name?.text ?? ""));
assert.equal(nodes.length, names.length);
const production = ts.transpileModule(nodes.map(n => n.getText(ast)).join("\n"), {
  compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS },
}).outputText;

async function main() {
  await client.connect();
  let cases = 0;
  try {
    // CTAS copies types only: no patient data, defaults, public sequences or FKs.
    for (const table of tables) await client.query(`CREATE TEMP TABLE ${table} AS SELECT * FROM public.${table} WITH NO DATA`);
    await client.query("SET search_path TO pg_temp");
    for (const table of tables) {
      const resolved = await client.query("SELECT to_regclass($1)::oid = to_regclass($2)::oid AS isolated", [table, `pg_temp.${table}`]);
      assert.equal(resolved.rows[0].isolated, true);
    }
    // Exercise only the video's additive migration against the private table.
    const migration = readFileSync(new URL("../../scripts/exercises_pg.sql", import.meta.url), "utf8");
    const videoColumns = migration.match(/^ALTER TABLE exercises ADD COLUMN IF NOT EXISTS (?:video_mime_type|youtube_video_id|video_file_name)[^;]+;/gm) ?? [];
    assert.equal(videoColumns.length, 3);
    for (let repeat = 0; repeat < 2; repeat++) for (const sql of videoColumns) await client.query(sql);
    for (const table of ["patient_exercises", "exercise_occurrences", "program_exercises"]) {
      await client.query(`ALTER TABLE pg_temp.${table} ALTER COLUMN id SET NOT NULL`);
      await client.query(`ALTER TABLE pg_temp.${table} ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY`);
    }
    await client.query("ALTER TABLE pg_temp.exercises ALTER COLUMN created_at SET DEFAULT now()");
    await client.query("ALTER TABLE pg_temp.patient_exercises ALTER COLUMN status SET DEFAULT 'pending'");
    await client.query("ALTER TABLE pg_temp.exercise_occurrences ALTER COLUMN status SET DEFAULT 'pending'");
    await client.query("CREATE UNIQUE INDEX ON pg_temp.patient_exercises (exercise_id, patient_id) WHERE archived_at IS NULL");
    await client.query("CREATE UNIQUE INDEX ON pg_temp.exercise_occurrences (patient_exercise_id, due_date)");
    const queries: string[] = [];
    const query = (sql: string, values?: any[]) => {
      assert(!/\bpublic\s*\./i.test(sql), "production SQL must not escape the private fixtures");
      assert(/^\s*(SELECT\b|BEGIN\b|COMMIT\b|ROLLBACK\b|INSERT INTO (patient_exercises|exercise_occurrences|exercise_programs|program_exercises)\b|UPDATE (exercises|patient_exercises|exercise_occurrences|program_exercises)\b|DELETE FROM exercises\b)/i.test(sql), sql);
      queries.push(sql);
      return client.query(sql, values);
    };
    const pool = { query, connect: async () => ({ query, release() {} }) };
    const context: any = vm.createContext({ exports: {}, pool, console,
      todayKeyPH: async () => "2026-10-30", DEFAULT_REST_SECONDS: 60, DEFAULT_HOLD_SECONDS: 30,
      generateSchedule, MAX_INTERVAL_DAYS, PRESCRIPTION_SNAPSHOT_VERSION, exerciseVideoFileFromRow,
    });
    vm.runInContext(production, context);
    const db = context.exports;
    const check = async (name: string, run: () => Promise<void>) => { await run(); cases++; console.log(`PASS ${name}`); };
    const seed = async (id: string, old = false) => client.query(
      "INSERT INTO exercises (id,name,description,is_custom,owner_therapist_id,monitoring_mode,created_at,youtube_video_id) VALUES ($1,'Disposable fixture','Disposable fixture',true,'fixture-owner','manual',now() - $2::interval,'dQw4w9WgXcQ')",
      [id, old ? "11 minutes" : "0 minutes"],
    );
    const snapshot = async () => {
      const state: any = {};
      for (const table of tables) state[table] = (await client.query(`SELECT to_jsonb(t) AS row FROM pg_temp.${table} t ORDER BY id`)).rows;
      return JSON.stringify(state);
    };
    const pe = async (id: string, patient = "fixture-other-patient", archived = false) => {
      const row = await client.query("INSERT INTO patient_exercises (exercise_id,patient_id,archived_at) VALUES ($1,$2,CASE WHEN $3 THEN now() END) RETURNING id", [id,patient,archived]);
      await client.query("INSERT INTO exercise_occurrences (patient_exercise_id,due_date,makeup_until,status) VALUES ($1,'2026-10-30','2026-10-30','pending')", [row.rows[0].id]);
    };
    await check("archive refuses another therapist's prescription without changing any row", async () => {
      await seed("fixture_shared"); await pe("fixture_shared");
      const before = await snapshot();
      await assert.rejects(() => db.archiveExercise("fixture_shared","fixture-owner"), db.ExerciseInUseError);
      assert.equal(await snapshot(),before);
    });
    await check("archive refuses program-only use without unlinking it", async () => {
      await seed("fixture_program");
      await client.query("INSERT INTO program_exercises (program_id,exercise_id,name) VALUES ('other-program','fixture_program','Fixture')");
      const before = await snapshot();
      await assert.rejects(() => db.archiveExercise("fixture_program","fixture-owner"),db.ExerciseInUseError);
      assert.equal(await snapshot(),before);
    });
    await check("an unused exercise can be archived and restored", async () => {
      await seed("fixture_unused");
      assert.equal(await db.archiveExercise("fixture_unused","fixture-owner"),true);
      assert((await db.getExerciseById("fixture_unused",true)).archived_at);
      assert.equal((await db.restoreExercise("fixture_unused")).archived_at,null);
    });
    for (const kind of ["prescription","archived-prescription","session","program"] as const) {
      await check(`draft cleanup preserves ${kind} history without side effects`, async () => {
        const id = `fixture_draft_${kind}`; await seed(id);
        if (kind.includes("prescription")) await pe(id,"fixture-other-patient",kind === "archived-prescription");
        if (kind === "session") await client.query("INSERT INTO sessions (id,exercise_id) VALUES (9001,$1)",[id]);
        if (kind === "program") await client.query("INSERT INTO program_exercises (program_id,exercise_id,name) VALUES ('other-program',$1,'Fixture')",[id]);
        const before = await snapshot();
        assert.equal(await db.discardNewExercise(id),"has-history");
        assert.equal(await snapshot(),before);
      });
    }
    await check("old drafts are kept and unused recent drafts alone are deleted", async () => {
      await seed("fixture_old",true); const before = await snapshot();
      assert.equal(await db.discardNewExercise("fixture_old"),"not-new");
      assert.equal(await snapshot(),before);
      await seed("fixture_disposable");
      assert.equal(await db.discardNewExercise("fixture_disposable"),"deleted");
      assert.equal(await snapshot(),before);
    });
    await check("patient catalog and file access agree on prescription ownership", async () => {
      await seed("fixture_assigned"); await seed("fixture_unassigned");
      await pe("fixture_assigned","fixture-patient");
      const exercises = await db.getExercises({ patientId:"fixture-patient" });
      assert.deepEqual(exercises.map((e: any) => e.id),["fixture_assigned"]);
      assert.equal(await db.canViewExerciseVideo({id:"fixture-patient",role:"patient"},await db.getExerciseById("fixture_unassigned")),false);
      assert((await db.getExercises()).some((e: any) => e.id === "fixture_unassigned"));
    });
    await check("real assignment SQL holds the catalog lock and creates an intact occurrence", async () => {
      await seed("fixture_assign");
      await db.assignExercisesToPatient("fixture-patient",[{
        exerciseId:"fixture_assign",sets:1,reps:3,restSeconds:60,holdSeconds:30,sequenceIndex:1,
        prescribedSide:"both",resistance:{type:"none",value:null,unit:null,label:null},
        scheduledDate:"2026-10-30",endDate:"2026-10-30",recurrence:"interval",intervalDays:1,
      }],"fixture-therapist");
      assert(queries.some(sql => /WHERE id = ANY/.test(sql) && /ORDER BY id FOR SHARE/.test(sql)));
      const before = await snapshot();
      await assert.rejects(() => db.archiveExercise("fixture_assign","fixture-owner"),db.ExerciseInUseError);
      assert.equal(await snapshot(),before);
      const occurrence = await client.query("SELECT prescription_snapshot FROM exercise_occurrences WHERE patient_exercise_id IN (SELECT id FROM patient_exercises WHERE exercise_id='fixture_assign')");
      assert.equal(occurrence.rows[0].prescription_snapshot.exerciseId,"fixture_assign");
    });
    await check("real program creation keeps shared exercise access and blocks archive", async () => {
      await seed("fixture_new_program");
      const id = await db.createProgram({therapistId:"fixture-other-therapist",name:"Fixture",exercises:[{
        exerciseId:"fixture_new_program",name:"Fixture",isCustom:true,sets:1,reps:3,sequenceIndex:1,
        prescribedSide:"both",resistance:{type:"none",value:null,unit:null,label:null},
      }]});
      assert.equal((await client.query("SELECT count(*)::int AS count FROM program_exercises WHERE program_id=$1",[id])).rows[0].count,1);
      const before = await snapshot();
      await assert.rejects(() => db.archiveExercise("fixture_new_program","fixture-owner"),db.ExerciseInUseError);
      assert.equal(await snapshot(),before);
    });
    await check("video publication returns the exact superseded file and preserves legacy references", async () => {
      await seed("fixture_video");
      await client.query("UPDATE exercises SET video_mime_type='video/mp4' WHERE id='fixture_video'");
      const a = await db.setExerciseVideoFile("fixture_video","video/mp4",`fixture_video.${"a".repeat(32)}.mp4`);
      assert.equal(a.previousVideo.mimeType,"video/mp4"); assert.equal(a.previousVideo.fileName,null);
      const b = await db.setExerciseVideoFile("fixture_video","video/webm",`fixture_video.${"b".repeat(32)}.webm`);
      assert.equal(b.previousVideo.fileName,a.exercise.video_file_name);
      assert.equal((await db.getExerciseById("fixture_video")).video_file_name,b.exercise.video_file_name);
      await db.archiveExercise("fixture_video","fixture-owner");
      assert.equal(await db.setExerciseVideoFile("fixture_video","video/mp4",`fixture_video.${"c".repeat(32)}.mp4`),null);
    });
    await check("permanent deletion still preserves archived prescription history", async () => {
      await seed("fixture_permanent_used"); await pe("fixture_permanent_used","fixture-other-patient",true);
      assert.equal(await db.archiveExercise("fixture_permanent_used","fixture-owner"),true);
      const before = await snapshot();
      assert.equal(await db.deleteArchivedExercise("fixture_permanent_used"),"has-history");
      assert.equal(await snapshot(),before);
      await seed("fixture_permanent_unused"); await db.archiveExercise("fixture_permanent_unused","fixture-owner");
      assert.equal(await db.deleteArchivedExercise("fixture_permanent_unused"),"deleted");
    });
    console.log(`${cases}/${cases} private-table exercise lifecycle cases passed; no public rows or sequences changed.`);
  } finally { await client.end(); }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
