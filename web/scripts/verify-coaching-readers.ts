/** Opt-in PostgreSQL acceptance. All fixture tables live in one private pg_temp
 * schema and disappear when its connection closes. No public row or sequence
 * is changed. Exercises actual production SQL, route, outbox and UI readers.
 */
/* eslint-disable @typescript-eslint/no-explicit-any */
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import vm from "node:vm";
import { Client } from "pg";
import { loadEnvConfig } from "@next/env";
import ts from "typescript";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { createCameraReplay, transpile } from "./lib/cameraReplayHarness";
import { getExerciseDefinition } from "../src/lib/exercises/registry";
import { captureCoachingProvenance } from "../src/lib/pose/coachingConfig";
import * as hold from "../src/lib/pose/holdQuality";
import * as versioning from "../src/lib/exercises/versioning";
import * as context from "../src/lib/prescriptionContext";
import * as readModels from "../src/lib/sessionReadModels";
import * as trendRules from "../src/lib/analytics/trendRules";
import { measureFromDetail } from "../src/lib/analytics/trendBreakdown";
import { EventOutbox } from "../src/lib/pose/eventOutbox";
import { groupSessionsByExercise } from "../src/app/(app)/dashboard/_components/ExerciseTrends";
import ConsistencyCalendar from "../src/app/(app)/dashboard/patient/ConsistencyCalendar";
import { isOutcomeBearingSession, completedSessionDoseText } from "../src/lib/exercises/scheduleSessionSummary";

loadEnvConfig(process.cwd(), false, { info() {}, error() {} });
assert(process.env.DATABASE_URL, "DATABASE_URL is required for private temporary-table acceptance");
const client = new Client({ connectionString: process.env.DATABASE_URL });
const tables = ["users", "exercises", "sessions", "set_events", "rep_events", "session_reviews", "patient_exercises", "exercise_occurrences"];
const plain = (v: any) => JSON.parse(JSON.stringify(v));
const extract = (source: string, names: string[]) => {
  const ast = ts.createSourceFile("subject.ts", source, ts.ScriptTarget.Latest, true);
  const nodes = ast.statements.filter(n => (ts.isFunctionDeclaration(n) || ts.isClassDeclaration(n)) && names.includes(n.name?.text ?? ""));
  assert.equal(nodes.length, names.length);
  return nodes.map(n => n.getText(ast)).join("\n");
};

async function main() {
  await client.connect();
  // Column types only: no data, constraints, defaults or public sequences.
  for (const table of tables) await client.query(`CREATE TEMP TABLE ${table} AS SELECT * FROM public.${table} WITH NO DATA`);
  await client.query("SET search_path TO pg_temp, public");
  for (const table of tables) {
    const resolved = await client.query("SELECT to_regclass($1)::oid = to_regclass($2)::oid AS isolated", [table, `pg_temp.${table}`]);
    assert.equal(resolved.rows[0].isolated, true, `${table} must resolve to the private fixture`);
  }
  await client.query("CREATE UNIQUE INDEX ON pg_temp.set_events (session_id, set_index)");
  await client.query("ALTER TABLE pg_temp.session_reviews ALTER COLUMN id SET NOT NULL");
  await client.query("ALTER TABLE pg_temp.session_reviews ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY");
  await client.query("ALTER TABLE pg_temp.session_reviews ALTER COLUMN created_at SET DEFAULT now()");
  await client.query("INSERT INTO pg_temp.users (id, name, role, therapist_id, is_archived) VALUES ('fixture', 'DISPOSABLE temporary coaching reader', 'patient', 'fixture-therapist', false)");
  await client.query("INSERT INTO pg_temp.exercises (id, name) VALUES ('ex_001','Lateral Arm Raises'), ('ex_006','Arm Abduction at 90°')");
  for (let id = 1; id <= 7; id++) await client.query(
    "INSERT INTO pg_temp.sessions (id, patient_id, exercise_id, started_at, ended_at, end_reason) VALUES ($1,'fixture',$2,now(),now(),$3)",
    [id, id === 1 || id === 7 ? "ex_001" : "ex_006", id === 2 ? "pain" : "user"],
  );

  const query = (sql: string, values?: any[]) => {
    // These production functions may only read or write the two shadowed
    // fixture event tables; unexpected future mutations fail closed.
    assert(/^\s*(SELECT\b|BEGIN\b|COMMIT\b|ROLLBACK\b|INSERT INTO (set_events|session_reviews)\b)/i.test(sql));
    assert(!/\bpublic\s*\./i.test(sql));
    return client.query(sql, values);
  };
  const pool = { query, connect: async () => ({ query, release() {} }) };
  const db: any = vm.createContext({ exports: {}, pool, console, ...hold, ...context, ...readModels, ...trendRules,
    todayKeyPH: () => new Date().toLocaleDateString("en-CA", { timeZone: "Asia/Manila" }),
    // The demo clock is off here, so the app time is the real time.
    getEffectiveNow: async () => new Date() });
  const functions = ["insertSetEvents", "getSessionsForPatient", "getSessionDetail", "getTherapistRoster", "appendSessionReview", "SessionReviewUnavailableError"];
  vm.runInContext(transpile(extract(readFileSync(new URL("../src/lib/db.ts", import.meta.url), "utf8"), functions)), db);
  const route: any = vm.createContext({ exports: {}, console, require: (name: string) => {
    if (name === "next/server") return { NextResponse: { json: (body: any, init?: any) => new Response(JSON.stringify(body), { status: init?.status ?? 200 }) } };
    if (name === "@/lib/auth-server") return { getAuthenticatedUser: async () => ({ id: "fixture", role: "patient" }) };
    if (name === "@/lib/db") return { getSessionOwner: async () => "fixture", insertSetEvents: db.exports.insertSetEvents };
    if (name === "@/lib/pose/holdQuality") return hold;
    if (name === "@/lib/exercises/versioning") return versioning;
    throw new Error(`Unexpected route dependency: ${name}`);
  } });
  vm.runInContext(transpile(readFileSync(new URL("../src/app/api/sessions/[id]/set-events/route.ts", import.meta.url), "utf8")), route);
  const post = (id: number, sets: any[]) => route.exports.POST({ json: async () => ({ sets }) }, { params: Promise.resolve({ id: String(id) }) });
  const patientPost = async (id: number, sets: any[]) => {
    const response = await post(id, sets); assert.equal(response.status, 200); return response.json();
  };

  const poseContext: any = vm.createContext({ exports: {} });
  vm.runInContext(transpile(extract(readFileSync(new URL("../src/lib/pose/coachingMeasurement.test.ts", import.meta.url), "utf8"), ["pose"])), poseContext);
  const dynamic = getExerciseDefinition("ex_001")!;
  const iso = getExerciseDefinition("ex_006")!;
  const attempts: any[] = [];
  for (const [i, definition] of [dynamic, iso].entries()) {
    const replay = createCameraReplay(definition, await captureCoachingProvenance(definition));
    replay.tick({ tMs: 1000, noPerson: true });
    replay.context.subject.handleSessionEnd(i === 0 ? "user" : "pain");
    assert.equal(replay.sets.length, 1);
    const attempt = plain(replay.sets[0]);
    assert.equal(attempt.holdQuality.auditOnly, true);
    attempts.push(attempt);
    await patientPost(i + 1, [attempt]);
  }
  const movement = createCameraReplay(iso, await captureCoachingProvenance(iso));
  for (let i = 0; i < 12; i++) movement.tick({ tMs: 1000 + i * 100, landmarks: poseContext.exports.pose(90, 0), baselines: { scapLeft: 0.12 / 0.35, scapRight: 0.12 / 0.35 } });
  movement.end();
  const partial = plain(movement.sets[0]);
  assert(partial.holdQuality.leftInBandMs > 0);
  assert.equal(partial.pairedHoldMs, 0);
  assert.equal(hold.isAuditOnlyMeasurement(partial.holdQuality), false);
  const audited = { ...attempts[1], setIndex: 2, holdQuality: { ...attempts[1].holdQuality, meanCompensationScore: 1, minCompensationScore: 1 } };
  const malformedAudit = { ...attempts[1], setIndex: 3, holdQuality: { version: "future", auditOnly: true, meanCompensationScore: 99 } };
  await patientPost(3, [partial, audited, malformedAudit]);
  const malformed = { ...partial, setIndex: 2, holdQuality: { version: "future", meanCompensationScore: 99 } };
  const first = await patientPost(4, [partial, malformed]);
  assert.equal(first.quarantined.length, 1);
  assert.equal(first.inserted, 2);
  const outbox = new EventOutbox<any, any>({ schedule: () => undefined, fetchFn: async (_url, init) => post(4, JSON.parse(init!.body as string).sets) });
  outbox.setSession(4); outbox.enqueue("set", malformed); outbox.enqueue("set", { ...partial, setIndex: 3 });
  assert.equal(await outbox.flush("set"), "delivered");
  assert.equal(outbox.pendingCount(), 0);
  const legacy = plain(partial);
  for (const key of ["version", "coaching", "primaryUnits", "compensationScoreSource", "streakMode"]) delete legacy.holdQuality[key];
  await patientPost(5, [legacy]);
  await patientPost(6, [{ ...attempts[1], holdQuality: undefined }]); // Historical unmarked row remains an outcome.
  await client.query("INSERT INTO pg_temp.rep_events (session_id,rep_index,set_index,side,classification) VALUES (7,1,1,'left','partial')");

  const history = plain(await db.exports.getSessionsForPatient("fixture"));
  const byId = (id: number) => history.find((s: any) => s.id === id);
  for (const id of [1, 2]) {
    const s = byId(id);
    assert.equal(s.setCount, 0); assert.equal(s.totalReps, 0);
    assert.equal(s.totalTargetHoldMs, null); assert.equal(s.totalPairedHoldMs, null);
    assert.equal(s.avgAsymmetryIndex, null); assert.equal(s.reviewScore, null);
    assert.equal(isOutcomeBearingSession(s), false); assert.equal(completedSessionDoseText(s), null);
    const detail = plain(await db.exports.getSessionDetail(id));
    assert.equal(detail.sets.length, 0); assert.equal(detail.auditAttempts.length, 1);
    assert.deepEqual(detail.auditAttempts[0].holdQuality, attempts[id - 1].holdQuality);
    await assert.rejects(db.exports.appendSessionReview(id, "fixture-therapist", "acceptable"), /No sufficiently covered rule score/);
  }
  const real = byId(3);
  assert.equal(real.setCount, 1); assert.equal(real.totalTargetHoldMs, partial.targetHoldMs);
  assert.equal(real.totalLeftHoldMs, partial.holdQuality.leftInBandMs);
  assert.equal(real.avgAsymmetryIndex, partial.asymmetryIndex);
  assert.equal(real.reviewScore, partial.holdQuality.meanCompensationScore);
  const detail = plain(await db.exports.getSessionDetail(3));
  assert.equal(detail.sets.length, 1); assert.equal(detail.auditAttempts.length, 2);
  assert.deepEqual(detail.auditAttempts[1].holdQuality.original, malformedAudit.holdQuality);
  await db.exports.appendSessionReview(3, "fixture-therapist", "acceptable");
  const review = await client.query("SELECT score_value FROM pg_temp.session_reviews WHERE session_id=3");
  assert.equal(Number(review.rows[0].score_value), partial.holdQuality.meanCompensationScore);
  const poisoned = plain(await db.exports.getSessionDetail(4));
  assert.equal(poisoned.sets.length, 3);
  assert.deepEqual(poisoned.sets[1].holdQuality.original, malformed.holdQuality);
  assert.equal(byId(4).reviewScore, partial.holdQuality.meanCompensationScore);
  assert.equal(byId(5).setCount, 1); assert.equal(byId(6).setCount, 1); assert.equal(byId(7).totalReps, 1);
  const roster = plain(await db.exports.getTherapistRoster("fixture-therapist"));
  assert.equal(roster[0].totalSessions, 5);
  const groups = groupSessionsByExercise(history);
  assert.equal(groups.flatMap(g => g.sessions).length, 5);
  const calendar = (sessions: any[]) => renderToStaticMarkup(createElement(ConsistencyCalendar, { sessions, occurrences: [] }));
  assert.equal(calendar(history.filter((s: any) => s.id <= 2)), calendar([]), "audit attempts must not create routine days or streaks");
  assert.equal(calendar(history), calendar(history.filter((s: any) => s.id > 2)));

  // Trend data rule 4 in the session list SQL, against the breakdown's own
  // rebuild: session 8's first calibration recorded a still-head reading of -4,
  // its second (from 10:10) none; session 9 has no record at all.
  await client.query("INSERT INTO pg_temp.exercises (id, name) VALUES ('ex_004','Neck Lateral Flexion')");
  const neckRest = { rule: "neck_rest_reference_v1", epochs: [
    { from: "2026-10-19T10:00:00.000Z", offsetDeg: -4, frames: 400 },
    { from: "2026-10-19T10:10:00.000Z", offsetDeg: null, frames: 3 }] };
  await client.query(
    `INSERT INTO pg_temp.sessions (id, patient_id, exercise_id, started_at, ended_at, end_reason, capture_quality_summary)
     VALUES (8, 'fixture', 'ex_004', '2026-10-19T09:59:00Z', '2026-10-19T10:12:00Z', 'completed', $1),
            (9, 'fixture', 'ex_004', '2026-10-19T09:00:00Z', '2026-10-19T09:05:00Z', 'completed', NULL)`,
    [JSON.stringify({ framesTotal: 100, framesOk: 100, pctOk: 100, neckRest })]);
  const neckReps: [number, number, number, string, number, number][] = [
    [8, 1, 1, "left", 28, 5], [8, 2, 1, "right", 48, 6], [8, 3, 1, "left", 34, 7], [8, 4, 1, "right", 50, 8],
    [8, 5, 2, "left", 30, 700], [8, 6, 2, "right", 46, 701],
    [9, 1, 1, "left", 33, -3000], [9, 2, 1, "right", 47, -2999],
  ];
  for (const [sid, rep, set, side, peak, seconds] of neckReps) await client.query(
    `INSERT INTO pg_temp.rep_events (session_id, rep_index, set_index, side, peak_value, target_rom, classification,
       time_to_peak_ms, descent_ms, start_ts) VALUES ($1, $2, $3, $4, $5, 30, $6, 500, 400, $7)`,
    [sid, rep, set, side, peak, peak >= 30 ? "complete" : "partial", new Date(Date.parse("2026-10-19T10:00:00Z") + seconds * 1000).toISOString()]);
  const neckHistory = plain(await db.exports.getSessionsForPatient("fixture"));
  const s8 = neckHistory.find((s: any) => s.id === 8);
  const s9 = neckHistory.find((s: any) => s.id === 9);
  assert.equal(s8.trend.rulesVersion, "trend_rules_v2");
  assert.equal(s8.trend.leftReps, 3); assert.equal(s8.trend.peakLeftReps, 2, "set 2 has no resting reading");
  assert.equal(s8.trend.avgLeftPeakValue, 35, "28 and 34 from rest: 32 and 38");
  assert.equal(s8.trend.avgRightPeakValue, 45, "48 and 50 from rest: 44 and 46");
  assert.equal(s8.trend.completeLeftReps, 2, "28 saved partial is complete from rest");
  assert.equal(s8.avgLeftPeakValue, 92 / 3, "the plain columns stay as saved");
  const neckDetail = plain(await db.exports.getSessionDetail(8));
  const peakFromDetail = measureFromDetail(neckDetail, "peak", "left");
  assert.equal(peakFromDetail.value, s8.trend.avgLeftPeakValue, "SQL and breakdown agree");
  assert.equal(peakFromDetail.units, s8.trend.peakLeftReps);
  assert.equal(measureFromDetail(neckDetail, "completionPct", "left").value, 100 * s8.trend.completeLeftReps / s8.trend.peakLeftReps);
  assert.equal(s9.trend.peakLeftReps, 0); assert.equal(s9.trend.avgLeftPeakValue, null, "no record: no peak");
  assert.equal(s9.trend.leftReps, 1, "the repetition still counts");
  assert.equal(measureFromDetail(plain(await db.exports.getSessionDetail(9)), "peak", "left").units, 0);
  for (const id of [1, 3, 4]) {
    const before = byId(id).trend;
    const after = neckHistory.find((s: any) => s.id === id).trend;
    assert.deepEqual({ ...after, peakLeftReps: undefined, peakRightReps: undefined, rulesVersion: undefined },
      { ...before, peakLeftReps: undefined, peakRightReps: undefined, rulesVersion: undefined }, "other exercises unchanged");
    assert.equal(after.peakLeftReps, after.leftReps, "every repetition of another exercise counts for its peaks");
  }
  console.log(JSON.stringify({ status: "passed", sessions: history.length, outcomeSessions: roster[0].totalSessions,
    auditOnlySessions: 2, actualPostgres: true, authenticatedHttp: false, physicalCamera: false,
    checks: "actual camera End, route/quarantine, outbox continuation, SQL aggregates/detail/review/roster, legacy and one-sided outcomes, trend grouping, rendered consistency calendar, neck rest rule 4 (SQL against the breakdown)",
    persistence: "connection-private temporary tables; no public rows or sequences changed" }));
}
main().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => client.end());
